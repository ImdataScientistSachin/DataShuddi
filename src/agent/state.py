"""
DataShuddiState — 4-Tier Categorized State Definition.

State fields are explicitly categorized into 4 lifecycle tiers to prevent
mixing of concerns and enforce clear data flow contracts across all nodes.

Tiers:
    TIER 1: Immutable Inputs     — Set once at ingress, never mutated.
    TIER 2: Per-Run Runtime      — Mutated during node execution, reset per doc.
    TIER 3: Persisted Policy     — Loaded from LangGraph Store, version-controlled.
    TIER 4: Observability        — Read-only logging & metrics.
"""
from typing import Any

from typing_extensions import TypedDict


class DataShuddiState(TypedDict):
    """
    Complete state dictionary for the DataShuddi 8-node LangGraph pipeline.

    Every field is assigned to one of four lifecycle tiers:
        TIER 1 — Immutable Inputs (set at ingress, never mutated downstream)
        TIER 2 — Per-Run Runtime State (mutated by nodes, reset per document)
        TIER 3 — Persisted Learned Policy (loaded from LangGraph Store)
        TIER 4 — Observability & Metadata (read-only telemetry)
    """

    # ── TIER 1: IMMUTABLE INPUTS ──────────────────────────────────────────────
    doc_id: str           # SHA-256 hash of raw file content (thread_id for PostgresSaver)
    doc_path: str         # Original filesystem path to the source document
    source_system: str    # Source origin: "local" | "confluence" | "drive"
    mime_type: str        # MIME type: "application/pdf" | "application/vnd.openxmlformats-officedocument.wordprocessingml.document" | "text/plain"

    # ── TIER 2: PER-RUN RUNTIME STATE ─────────────────────────────────────────
    raw_text: str                         # Raw extracted text from the document
    _pages: list[str]                     # Page-separated text array (from Extractor)
    cleaned_text: str                     # Text after header/footer removal
    masked_text: str                      # Text after PII masking (Node 4 output)
    header_footer_candidates: list[str]   # Repeating lines flagged as H/F boilerplate
    pii_entities: list[dict[str, Any]]    # Detected PII entities from both layers
    pii_count: int                        # Total count of detected PII entities
    validation_errors: list[str]          # Pydantic validation error messages (Node 5)
    validation_passed: bool               # True if schema validation passed
    retry_count: int                      # Current retry attempt count (max: MAX_RETRY_COUNT)
    reflection_text: str                  # Critique text generated by Qwen14b Reflector
    reflector_confidence: float           # Reflector model confidence score (0.0 – 1.0)
    needs_human_review: bool              # True if escalated to human review queue

    # ── TIER 3: PERSISTED LEARNED POLICY ──────────────────────────────────────
    hf_threshold: float   # Dynamic H/F detection threshold (default: 0.30, versioned in Store)

    # ── TIER 4: OBSERVABILITY & METADATA ──────────────────────────────────────
    is_sanitized: bool                  # True after Node 0 security scan completes
    security_flags: list[str]           # List of triggered security rule descriptions
    quality_score: float                # Composite quality score (0.0 – 1.0)
    node_timestamps: dict[str, float]   # Execution timestamps per node {node_name: unix_ts}
    processing_time_ms: int             # Total end-to-end processing time in milliseconds
    _start_time: float                  # Pipeline execution start timestamp (unix)


def create_initial_state(
    doc_id: str,
    doc_path: str,
    source_system: str = "local",
    mime_type: str = "text/plain",
    raw_text: str = "",
    pages: list[str] | None = None,
    hf_threshold: float = 0.30,
) -> DataShuddiState:
    """
    Factory function constructing a clean, fully initialized DataShuddiState dictionary.

    Args:
        doc_id: Unique SHA-256 string hash of the target document.
        doc_path: Path string to the source document on disk.
        source_system: Source classification ("local", "hr_docs", "legal", etc.).
        mime_type: MIME type string.
        raw_text: Pre-extracted raw text (optional, defaults to empty).
        pages: Pre-split page array (optional, defaults to empty).
        hf_threshold: Header/footer frequency threshold (defaults to 0.30).

    Returns:
        Properly populated DataShuddiState instance.
    """
    import time

    return {
        "doc_id": doc_id,
        "doc_path": doc_path,
        "source_system": source_system,
        "mime_type": mime_type,
        "raw_text": raw_text,
        "_pages": pages if pages is not None else [],
        "cleaned_text": "",
        "masked_text": "",
        "header_footer_candidates": [],
        "pii_entities": [],
        "pii_count": 0,
        "validation_errors": [],
        "validation_passed": False,
        "retry_count": 0,
        "reflection_text": "",
        "reflector_confidence": 0.0,
        "needs_human_review": False,
        "hf_threshold": hf_threshold,
        "is_sanitized": False,
        "security_flags": [],
        "quality_score": 0.0,
        "node_timestamps": {},
        "processing_time_ms": 0,
        "_start_time": time.time(),
    }
